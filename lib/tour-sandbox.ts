/**
 * Promotion sandbox → production (admin) : autorisée seulement après approbation
 * pour les parcours développeur (rejeté ou en attente bloquent le passage prod).
 */
/** Switcher sandbox ↔ prod : propriétaire admin pour ses parcours ; modérateur pour les parcours développeur. */
export function canAdminTransferTourEnvironment(
	tour: TourSandboxFields &
		Pick<
			GuidedTour,
			| 'accessGrants'
			| 'createdBy'
			| 'inCollaboration'
			| 'triggerConditions'
			| 'developerPrivate'
			| 'assignedAdminIds'
		>,
	role: DashboardRole | null,
	userId?: string,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	if (role !== 'ADMIN' || !userId) {
		return false;
	}
	if (isTourCardViewOnly(tour, role, userId) || isTourCollaborationPeerCard(tour, role, userId)) {
		return false;
	}
	if (isAdminOriginatedTour(tour, creatorRoleByUserId)) {
		if (isTourProductionDeployment(tour)) {
			return isProductionManagerAdmin(tour, userId, creatorRoleByUserId);
		}
		return tour.createdBy === userId;
	}
	if (tour.createdBy === userId) {
		return true;
	}
	return resolveTourEditorAccess(tour, role, userId, null) === 'admin';
}

/** Repasser un parcours admin de prod → sandbox : réservé au propriétaire créateur. */
export function canAdminTransferProductionToSandbox(
	tour: TourOriginFields,
	role: DashboardRole | null,
	userId?: string,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	if (tour.environment !== 'production') {
		return true;
	}
	if (!isAdminOriginatedTour(tour, creatorRoleByUserId)) {
		return canAdminTransferTourEnvironment(tour, role, userId, creatorRoleByUserId);
	}
	return Boolean(userId) && tour.createdBy === userId;
}

export function canAdminTransferSandboxToProduction(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	if (tour.environment !== 'sandbox') {
		return true;
	}
	if (isDeveloperSubmittedPendingSandbox(tour, creatorRoleByUserId)) {
		return false;
	}
	if (isDeveloperModerationRejectedTour(tour, creatorRoleByUserId)) {
		return false;
	}
	if (isReturnedSandboxTour(tour)) {
		return false;
	}
	return true;
}

export function matchesTourEnvironmentFilter(
	tour: TourSandboxFields,
	filter: TourListEnvironmentFilter,
): boolean {
	switch (filter) {
		case 'production':
			return tour.environment === 'production' || !tour.environment;
		case 'sandbox':
			return tour.environment === 'sandbox' || isDeveloperOnlyAutogenTour(tour);
		case 'pending':
			return isPendingSandboxTour(tour);
		case 'lecture':
			return Boolean(
				(tour as Pick<GuidedTour, 'sharingHasView'>).sharingHasView,
			);
		case 'collab':
			return Boolean(
				(tour as Pick<GuidedTour, 'sharingHasCollaborate'>).sharingHasCollaborate,
			);
		default:
			return true;
	}
}

