export type TourCreatorRoleLookup = ReadonlyMap<string, 'ADMIN' | 'DEVELOPER' | 'USER'>;

type TourOriginFields = TourSandboxFields & Pick<GuidedTour, 'triggerConditions' | 'createdBy'>;

/** Parcours issu d’un développeur (file modération), distinct de l’environnement sandbox admin. */
export function isDeveloperOriginatedTour(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	const publishedRole = getContextualPublishedByRole(tour)?.toUpperCase();
	const createdBy = tour.createdBy?.trim();
	const creatorRole = createdBy ? creatorRoleByUserId?.get(createdBy) : undefined;

	if (publishedRole === 'ADMIN') {
		return false;
	}
	if (publishedRole === 'DEVELOPER') {
		return true;
	}
	if (publishedRole === 'SDK_TOKEN') {
		if (!createdBy) {
			return false;
		}
		if (Boolean(tour.developerPrivate)) {
			return true;
		}
		if (normalizeAssignedAdminIds(tour.assignedAdminIds).length > 0) {
			return true;
		}
		if (tour.sandboxStatus === 'approved') {
			return true;
		}
		return creatorRole === 'DEVELOPER';
	}

	if (isContextualAutogeneratedTour(tour)) {
		// Autogen legacy en sandbox : developerPrivate distingue admin (false) vs développeur (true).
		if (tour.environment !== 'sandbox' || !createdBy) {
			if (creatorRole === 'DEVELOPER' && tour.sandboxStatus === 'approved') {
				return true;
			}
			return false;
		}
		if (creatorRole === 'ADMIN') {
			return false;
		}
		if (creatorRole === 'DEVELOPER') {
			return true;
		}
		return Boolean(tour.developerPrivate);
	}

	if (!createdBy) {
		return false;
	}

	if (creatorRole === 'ADMIN') {
		return false;
	}
	if (creatorRole === 'DEVELOPER') {
		return true;
	}

	// Parcours manuel sans rôle créateur connu : aligné backend via developerPrivate.
	return Boolean(tour.developerPrivate);
}

/** Parcours admin (hors file modération développeur). */
export function isAdminOriginatedTour(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	return Boolean(tour.createdBy?.trim()) && !isDeveloperOriginatedTour(tour, creatorRoleByUserId);
}

/** Parcours admin en sandbox : visible uniquement par le propriétaire (+ invités par grant). */
export function isAdminSandboxPrivateTour(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	return isAdminOriginatedTour(tour, creatorRoleByUserId) && tour.environment === 'sandbox';
}

/** Parcours admin publié en production (gestion déléguée possible). */
export function isAdminOriginatedProductionTour(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	return isTourProductionDeployment(tour) && isAdminOriginatedTour(tour, creatorRoleByUserId);
}

export function resolveProductionManagerAdminId(
	tour: Pick<GuidedTour, 'createdBy' | 'productionManagedByAdminId'>,
): string | null {
	if (tour.productionManagedByAdminId) {
		return tour.productionManagedByAdminId;
	}
	return tour.createdBy ?? null;
}

export function isProductionManagerAdmin(
	tour: TourOriginFields,
	userId?: string,
	creatorRoleByUserId?: TourCreatorRoleLookup,
): boolean {
	if (!userId || !isAdminOriginatedProductionTour(tour, creatorRoleByUserId)) {
		return false;
	}
	return resolveProductionManagerAdminId(tour) === userId;
}

/** Propriétaire créateur : déléguer ou reprendre la gestion prod. */
