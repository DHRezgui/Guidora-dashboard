export function getTourAccessGrant(
	tour: Pick<GuidedTour, 'accessGrants'>,
	userId?: string,
	mode?: TourAccessMode,
) {
	if (!userId || !tour.accessGrants?.length) {
		return undefined;
	}
	const grant = tour.accessGrants.find((g) => g.userId === userId);
	if (!mode) {
		return grant;
	}
	return grant?.accessMode === mode ? grant : undefined;
}

export function hasTourAccessGrant(
	tour: Pick<GuidedTour, 'accessGrants'>,
	userId: string | undefined,
	mode: TourAccessMode,
): boolean {
	return Boolean(getTourAccessGrant(tour, userId, mode));
}

/** Duplication / concaténation : interdit en accès lecture seule. */
export function canForkTour(
	tour: Pick<
		GuidedTour,
		| 'accessGrants'
		| 'createdBy'
		| 'inCollaboration'
		| 'environment'
		| 'sandboxStatus'
		| 'assignedAdminIds'
		| 'targetUrl'
		| 'triggerConditions'
		| 'productionManagedByAdminId'
	>,
	role: DashboardRole | null,
	userId?: string,
): boolean {
	if (!userId || isSdkLabTemplateTour(tour)) {
		return false;
	}
	if (isTourProductionDeployment(tour)) {
		if (!isProductionManagerAdmin(tour, userId)) {
			return false;
		}
		if (tour.createdBy === userId) {
			return !isDeveloperOwnedAwaitingAdminDecision(tour, userId);
		}
		return isAdminOriginatedTour(tour);
	}
	if (isTourCollaborationPeerCard(tour, role, userId)) {
		return false;
	}
	if (tour.createdBy === userId) {
		return !isDeveloperOwnedAwaitingAdminDecision(tour, userId);
	}
	const mode = resolveTourEditorAccess(tour, role, userId, null);
	return mode !== null && mode !== 'view';
}

