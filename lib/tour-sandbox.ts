const OWNERSHIP_TRANSFER_REASON_PREFIX = 'Parcours transféré à un autre développeur';

/** Parcours renvoyé suite à un transfert de propriété (distinct du renvoi modération classique). */
export function isOwnershipTransferReturn(
	tour: Pick<GuidedTour, 'sandboxStatus' | 'sandboxRejectionReason'>,
): boolean {
	return (
		tour.sandboxStatus === 'returned' &&
		Boolean(tour.sandboxRejectionReason?.includes(OWNERSHIP_TRANSFER_REASON_PREFIX))
	);
}

/** Motif lisible affiché dans le badge / modal Transféré. */
export function getOwnershipTransferMessage(
	tour: Pick<GuidedTour, 'sandboxRejectionReason'>,
): string | null {
	if (!isOwnershipTransferReturn(tour)) {
		return null;
	}
	const reason = tour.sandboxRejectionReason?.trim() ?? '';
	const marker = 'Motif : ';
	const markerIndex = reason.indexOf(marker);
	if (markerIndex >= 0) {
		return reason.slice(markerIndex + marker.length).trim() || null;
	}
	return reason || null;
}

/** Ancien propriétaire : accès lecture conservé après transfert. */
export function isPreviousOwnerOfTransferredTour(
	tour: Pick<GuidedTour, 'createdBy' | 'sandboxStatus' | 'sandboxRejectionReason' | 'accessGrants'>,
	userId?: string,
): boolean {
	if (!userId || !isOwnershipTransferReturn(tour) || tour.createdBy === userId) {
		return false;
	}
	return hasTourAccessGrant(tour, userId, 'view');
}

export function formatTourActorLabel(
	user?: Pick<User, 'firstName' | 'lastName' | 'email'> | null,
	fallback = 'Administrateur',
): string {
	if (!user) {
		return fallback;
	}
	const name = [user.firstName, user.lastName].filter(Boolean).join(' ').trim();
	return name ? `${name} (${user.email})` : user.email || fallback;
}

export function resolveTourActorLabel(
	actorId: string | null | undefined,
	usersById?: ReadonlyMap<string, Pick<User, 'firstName' | 'lastName' | 'email'>>,
	sessionUser?: Pick<User, 'id' | 'firstName' | 'lastName' | 'email'> | null,
): string {
	if (!actorId) {
		return 'Inconnu';
	}
	if (sessionUser?.id === actorId) {
		return formatTourActorLabel(sessionUser, 'Vous');
	}
	return formatTourActorLabel(usersById?.get(actorId), 'Administrateur');
}

/** Libellé court pour le badge « Gestion » (évite le chevauchement avec le titre / la date). */
export function formatProductionManagerShortLabel(
	actorId: string | null | undefined,
	usersById?: ReadonlyMap<string, Pick<User, 'firstName' | 'lastName' | 'email'>>,
	sessionUser?: Pick<User, 'id' | 'firstName' | 'lastName' | 'email'> | null,
): string {
	if (!actorId) {
		return 'Inconnu';
	}
	if (sessionUser?.id === actorId) {
		return 'Vous';
	}
	const user = usersById?.get(actorId);
	const name = [user?.firstName, user?.lastName].filter(Boolean).join(' ').trim();
	if (name) {
		return name;
	}
	const email = user?.email?.trim();
	if (email) {
		const local = email.split('@')[0]?.trim();
		return local || email;
	}
	return 'Admin';
}

