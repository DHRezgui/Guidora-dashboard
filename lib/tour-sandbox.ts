/** En attente de validation admin (parcours développeur uniquement). */
export function isDeveloperSubmittedPendingSandbox(
	tour: TourOriginFields,
	creatorRoleByUserId?: TourCreatorRoleLookup,
	viewer?: { role: DashboardRole | null; userId?: string },
): boolean {
	if (!isPendingSandboxTour(tour) || !isDeveloperOriginatedTour(tour, creatorRoleByUserId)) {
		return false;
	}
	if (viewer?.role === 'DEVELOPER') {
		return (
			isPendingSandboxTour(tour) &&
			normalizeAssignedAdminIds(tour.assignedAdminIds).length > 0
		);
	}
	if (viewer?.role === 'ADMIN') {
		return isTourAssignedToAdmin(tour, viewer.userId);
	}
	return isPendingSandboxTour(tour) && isDeveloperOriginatedTour(tour, creatorRoleByUserId);
}

