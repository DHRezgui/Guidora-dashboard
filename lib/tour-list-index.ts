export function resolveTourCardDisplayName(
	tour: Pick<GuidedTour, 'name' | 'targetUrl'>,
	isAutogen: boolean,
): string {
	const trimmed = tour.name?.trim();
	if (trimmed) {
		return trimmed;
	}
	if (isAutogen) {
		const path = tour.targetUrl?.trim();
		return path ? `Parcours autogénéré — ${path}` : 'Parcours autogénéré';
	}
	return 'Sans nom';
}

